"""Build this bank through a real serum-mcp stdio connection, then read it back.

Run from repository root with integrations/serum-mcp/.venv/Scripts/python.exe.
Destination revision must already have been generated by midi-creator.
"""
from pathlib import Path
from datetime import datetime, timedelta, timezone
import asyncio
import hashlib
import json
import math
import shutil
import subprocess
import sys
import argparse

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client
from serum_mcp.generation.spec import PresetSpec
from serum_mcp.preset.packer import unpack_file
from serum_mcp.preset.introspect import extract_spec
from serum_mcp.preset.safety import scan_wire_types
from serum_mcp.preset.wavetable import read_wav_mono
from serum_mcp.preset.schema import SIMPLE_WAVETABLES
from serum_mcp.tools._naming import sanitize_subfolder, slugify_preset_name
import numpy as np

SOURCE=Path(__file__).resolve().parent
WORKSPACE=Path.cwd().resolve()
cli=argparse.ArgumentParser(description=__doc__)
cli.add_argument('--revision',type=Path,default=WORKSPACE/'projects/20261016-neon-orbits/v003')
cli.add_argument('--bank',default='MIDI Creator/20261016-neon-orbits/v003')
cli.add_argument('--resume',action='store_true',help='Read existing files created by an interrupted build, without overwriting.')
ARGS=cli.parse_args()
REVISION=ARGS.revision.resolve()
OUT=REVISION/'_internal/serum-bank'
BANK=ARGS.bank

def save(path,value):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def contains(actual,expected):
    if isinstance(expected,dict):
        return isinstance(actual,dict) and all(k in actual and contains(actual[k],v) for k,v in expected.items())
    if isinstance(expected,list):
        return isinstance(actual,list) and len(actual)>=len(expected) and all(contains(actual[i],v) for i,v in enumerate(expected))
    if type(expected) in (float,int) and type(actual) in (float,int):
        return math.isclose(actual,expected,abs_tol=1e-5,rel_tol=1e-5)
    return actual==expected

def unknown_keys(raw,model,path=''):
    fields=model.model_fields
    mapping={f.alias or k:f for k,f in fields.items()}
    for k,v in raw.items():
        if k not in mapping:raise ValueError(f'Unknown semantic field {path}.{k}')
    # Specs use model_validate; nested fields are additionally checked against
    # model_dump preserving submitted keys in the readback comparisons below.

async def main():
    assert (REVISION/'_internal/manifest.json').exists()
    OUT.mkdir(parents=True,exist_ok=False)
    (REVISION/'Presets').mkdir(exist_ok=True)
    cfg=json.loads((WORKSPACE/'studio.local.json').read_text(encoding='utf8'))
    root=Path(cfg['serum_presets']).parent
    presets=root/'Presets/User'
    repo=WORKSPACE/'integrations/serum-mcp'
    env={'SERUM_PRESETS_PATH':str(presets),'SERUM_TABLES_PATH':str(root/'Tables'),'SERUM_SAMPLES_PATH':str(root/'Samples')}
    params=StdioServerParameters(command=str(repo/'.venv/Scripts/python.exe'),args=['-m','serum_mcp.server'],cwd=str(repo),env=env)
    receipt={'ok':False,'created_at':datetime.now(timezone.utc).isoformat(),'commit':subprocess.check_output(['git','-C',str(repo),'rev-parse','HEAD'],text=True).strip(),'bank':BANK,'plugin_loaded':False,'audio_rendered':False,'listened':False,'presets':[]}
    try:
        async with stdio_client(params) as (reader,writer):
            async with ClientSession(reader,writer,read_timeout_seconds=timedelta(seconds=60)) as client:
                initialized=await client.initialize()
                available=await client.list_tools()
                save(OUT/'tool-schemas.json',[t.model_dump() for t in available.tools])
                receipt['server']=initialized.serverInfo.model_dump()
                async def call(name,args):
                    result=await client.call_tool(name,args)
                    if result.isError:raise RuntimeError(f'{name}: {result.content}')
                    return '\n'.join(b.text for b in result.content if b.type=='text')
                save(OUT/'parameters.json',json.loads(await call('list_parameters',{})))
                # Search existing banks before final creation to record palette context.
                refs={}
                for query in ['Juno','analog bass','pluck','glass']:
                    refs[query]=json.loads(await call('find_reference_presets',{'query':query,'limit':3}))
                save(OUT/'references.json',refs)
                resources={}
                for path in sorted((SOURCE/'preset-specs').glob('*.json')):
                    raw=json.loads(path.read_text(encoding='utf8'))
                    unknown_keys(raw,PresetSpec)
                    spec=PresetSpec.model_validate(raw)
                    # Inspect every used wavetable's actual source frames and resources.
                    for osc in raw['oscillators']:
                        if not osc.get('enabled'):continue
                        table=osc.get('wavetable','default')
                        rel=SIMPLE_WAVETABLES[table].relative_path if table in SIMPLE_WAVETABLES else table
                        rp=root/'Tables'/rel
                        samples,sr=read_wav_mono(rp)
                        fcount=len(samples)//2048
                        frame=osc.get('table_position',0)
                        assert 0<=frame<fcount,(table,frame,fcount)
                        data=samples[round(frame)*2048:(round(frame)+1)*2048]
                        mags=np.abs(np.fft.rfft(data))
                        resources[rel]={'file':str(rp),'sha256':hashlib.sha256(rp.read_bytes()).hexdigest(),'frames':fcount,'sample_rate':sr,'peak_selected_frame':float(np.max(np.abs(data))),'selected_frame':frame,'harmonic_ratios':(mags[1:9]/max(float(mags[1]),1e-12)).tolist(),'factory':True}
                    target=presets/sanitize_subfolder(BANK)/(slugify_preset_name(spec.name)+'.SerumPreset')
                    if target.exists():
                        if not ARGS.resume:raise FileExistsError(f'Preserve existing preset: {target}')
                        result=str(target)  # Read and check this task's existing result; never overwrite.
                    else:
                        result=await call('generate_preset',{'spec':raw,'subfolder':BANK})
                    generated=Path(result.splitlines()[0]).resolve()
                    assert generated==target.resolve(),result
                    desc=await call('describe_preset',{'preset_path':str(generated)})
                    preset=unpack_file(generated)
                    actual=extract_spec(preset.data).model_dump(by_alias=True)
                    issues=scan_wire_types(preset.data)
                    comparisons={}
                    for field in ('oscillators','filters','envelopes','lfos','macros','fx_chain','global','arp'):
                        if field in raw:comparisons[field]=contains(actual[field],raw[field])
                    if raw.get('arp')=={'enabled':False}:
                        # extract_spec intentionally represents a disabled arp as None.
                        comparisons['arp']=not bool(preset.data.get('Arp0',{}).get('plainParams',{}).get('kParamEnabled',False))
                    comparisons['mod_routes']=all(any(contains(r,w) for r in actual['mod_routes']) for w in raw.get('mod_routes',[]))
                    comparisons['name']=preset.metadata.get('presetName')==spec.name
                    item_dir=OUT/spec.name
                    save(item_dir/'readback.json',actual)
                    save(item_dir/'comparison.json',comparisons)
                    (item_dir/'description.txt').write_text(desc,encoding='utf8')
                    save(item_dir/'tool-response.json',{'result':result,'wire_type_issues':[str(i) for i in issues]})
                    if not all(comparisons.values()) or issues:raise ValueError(f'{spec.name} readback/scan failed: {comparisons}; {issues}')
                    delivered=REVISION/'Presets'/f'{spec.name}.SerumPreset'
                    if delivered.exists():raise FileExistsError(delivered)
                    shutil.copy2(generated,delivered)
                    sha=hashlib.sha256(delivered.read_bytes()).hexdigest()
                    assert sha==hashlib.sha256(generated.read_bytes()).hexdigest()
                    receipt['presets'].append({'id':spec.name,'installed':str(generated),'delivered':str(delivered),'sha256':sha,'structural_readback':comparisons,'wire_type_issues':[],'dependency_notes':result.splitlines()[1:]})
                    print(f'{spec.name}: native build, readback, wire scan, copied hash OK',flush=True)
                save(OUT/'resources.json',resources)
                receipt['ok']=True
    except BaseException as exc:
        receipt['error']=str(exc)
        raise
    finally:
        save(OUT/'receipt.json',receipt)
    print(json.dumps({'ok':receipt['ok'],'native_presets':len(receipt['presets']),'plugin_loaded':False,'listened':False}))

if __name__=='__main__':asyncio.run(main())
